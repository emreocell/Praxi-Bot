//! Keep the CLI command tree, `docs/guide/cli-reference.md`, and the generated
//! clap reference snapshot (`docs/cli/reference.md`) in step.
//!
//! The test runs the real `bot` binary with `--help`, walks the visible
//! subcommands, and compares commands, global and subcommand long flags, and
//! environment variables with the headings and command tables of the reference,
//! plus verifies that `docs/cli/reference.md` matches the live command tree.
//! Every mismatch is reported in one failure so a contributor can fix the whole
//! drift at once.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

const CLI_REFERENCE: &str = include_str!("../../../docs/guide/cli-reference.md");
const GENERATED_CLI_REFERENCE_PATH: &str = "docs/cli/reference.md";

/// Visible commands that are deliberately undocumented. Every entry needs a
/// reason; keep the list empty when you can.
const ALLOWED_MISSING: &[(&str, &str)] = &[];

/// Long flags that are deliberately undocumented, as `(command, flag, reason)`.
const ALLOWED_MISSING_FLAGS: &[(&str, &str, &str)] = &[];

/// Environment variables that are deliberately undocumented, with a reason.
const ALLOWED_MISSING_ENV: &[(&str, &str)] = &[];

/// Parsed pieces of one `bot ... --help` output.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
struct Help {
    about: String,
    children: Vec<String>,
    flags: BTreeSet<String>,
    env: BTreeSet<String>,
}

fn run_help(path: &[String]) -> String {
    let mut command = Command::new(env!("CARGO_BIN_EXE_bot"));
    command
        .args(path)
        .arg("--help")
        .env("NO_COLOR", "1")
        .env("COLUMNS", "120");
    let output = command
        .output()
        .unwrap_or_else(|error| panic!("could not run `bot {} --help`: {error}", path.join(" ")));
    assert!(
        output.status.success(),
        "`bot {} --help` failed: {}",
        path.join(" "),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).expect("`bot --help` prints UTF-8")
}

fn parse_help(text: &str) -> Help {
    let mut help = Help::default();
    let mut section = "";
    let mut before_usage = true;
    for line in text.lines() {
        let heading = line.trim_end();
        if heading.starts_with("Usage:") {
            before_usage = false;
        } else if before_usage && help.about.is_empty() && !heading.trim().is_empty() {
            heading.trim().clone_into(&mut help.about);
        }
        if !line.starts_with(' ') && heading.ends_with(':') {
            section = heading.trim_end_matches(':');
        }
        if section == "Commands"
            && let Some(rest) = line.strip_prefix("  ")
            && !rest.starts_with(' ')
            && let Some(name) = rest.split_whitespace().next()
        {
            help.children.push(name.to_owned());
        }
        if matches!(section, "Options" | "Global Options")
            && let Some(flag) = option_flag(line)
        {
            help.flags.insert(flag.to_owned());
        }
        if let Some(name) = env_name(line) {
            help.env.insert(name.to_owned());
        }
    }
    help
}

/// The long flag on an option line. Clap indents a short option by two spaces
/// and a long-only option by six; description lines are indented further.
fn option_flag(line: &str) -> Option<&str> {
    let rest = line.strip_prefix("  ")?;
    let rest = rest.strip_prefix("    ").unwrap_or(rest);
    let mut words = rest.split_whitespace();
    let first = words.next()?;
    if first.starts_with("--") {
        return Some(first.trim_end_matches(','));
    }
    if first.starts_with('-') && first.ends_with(',') {
        let second = words.next()?;
        if second.starts_with("--") {
            return Some(second.trim_end_matches(','));
        }
    }
    None
}

fn env_name(line: &str) -> Option<&str> {
    let rest = line.split_once("[env: ")?.1;
    let end = rest
        .find(|c: char| !(c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_'))
        .unwrap_or(rest.len());
    (end > 0).then(|| &rest[..end])
}

fn display_path(path: &[String]) -> String {
    if path.is_empty() {
        "bot".to_owned()
    } else {
        format!("bot {}", path.join(" "))
    }
}

fn collect(path: &mut Vec<String>, out: &mut BTreeMap<String, Help>) {
    let text = run_help(path);
    let help = parse_help(&text);
    let children = help.children.clone();
    out.insert(display_path(path), help);
    for child in children {
        // `help` is generated by clap for every command level, has no
        // `--help` of its own, and is documented as `bot --help`.
        if child == "help" {
            continue;
        }
        path.push(child);
        collect(path, out);
        path.pop();
    }
}

/// The command headings, command-table rows and section bodies of the guide.
struct Reference<'a> {
    /// Documented command path -> 1-based line number of its first mention.
    commands: BTreeMap<String, usize>,
    /// Documented command path -> the body of its heading, until the next one.
    sections: BTreeMap<String, String>,
    /// Body of the `## Global options` section.
    global_options: String,
    text: &'a str,
}

impl<'a> Reference<'a> {
    fn parse() -> Self {
        Self::parse_str(CLI_REFERENCE)
    }

    fn parse_str(source: &'a str) -> Self {
        let mut commands = BTreeMap::new();
        let mut sections = BTreeMap::new();
        let mut headings: Vec<String> = Vec::new();
        let mut body = String::new();
        let mut global_options = String::new();
        let mut in_global_options = false;
        let mut in_fence = false;

        for (index, line) in source.lines().enumerate() {
            if line.starts_with("```") {
                in_fence = !in_fence;
                if !headings.is_empty() {
                    body.push_str(line);
                    body.push('\n');
                }
                if in_global_options {
                    global_options.push_str(line);
                    global_options.push('\n');
                }
                continue;
            }
            if in_fence {
                if !headings.is_empty() {
                    body.push_str(line);
                    body.push('\n');
                }
                if in_global_options {
                    global_options.push_str(line);
                    global_options.push('\n');
                }
                continue;
            }
            if let Some(title) = line.strip_prefix("### ") {
                flush(&mut sections, &headings, &mut body);
                in_global_options = false;
                headings = heading_paths(title);
                for path in &headings {
                    commands.entry(path.clone()).or_insert(index + 1);
                }
                continue;
            }
            if let Some(h2) = line.strip_prefix("## ") {
                flush(&mut sections, &headings, &mut body);
                headings.clear();
                in_global_options = h2.trim().eq_ignore_ascii_case("Global options");
                continue;
            }
            if in_global_options {
                global_options.push_str(line);
                global_options.push('\n');
            }
            if let Some(section) = headings.first()
                && let Some(path) = table_row_path(line, section)
            {
                commands.entry(path).or_insert(index + 1);
            }
            if !headings.is_empty() {
                body.push_str(line);
                body.push('\n');
            }
        }
        flush(&mut sections, &headings, &mut body);

        Self {
            commands,
            sections,
            global_options,
            text: source,
        }
    }

    /// The section body that documents `path`, falling back to its closest
    /// documented ancestor (subcommands are often rows in the parent table).
    fn section(&self, path: &str) -> Option<&str> {
        let mut current = path;
        loop {
            if let Some(body) = self.sections.get(current) {
                return Some(body);
            }
            let (parent, _) = current.rsplit_once(' ')?;
            current = parent;
        }
    }
}

fn flush(sections: &mut BTreeMap<String, String>, headings: &[String], body: &mut String) {
    for heading in headings {
        sections.insert(heading.clone(), body.clone());
    }
    body.clear();
}

/// Command paths in a `###` heading. A heading may list alternatives, as in
/// `bot backup create | verify | restore`.
fn heading_paths(title: &str) -> Vec<String> {
    let title = title.trim();
    let title = title.strip_prefix('`').unwrap_or(title);
    let title = title.strip_suffix('`').unwrap_or(title);
    let mut parts = title.split('|').map(str::trim);
    let Some(first) = parts.next() else {
        return Vec::new();
    };
    let base = command_words(first);
    let Some((_, prefix)) = base.split_last() else {
        return Vec::new();
    };
    let mut paths = vec![base.join(" ")];
    for alternative in parts {
        if let Some(word) = alternative.split_whitespace().next()
            && is_command_word(word)
        {
            let mut path = prefix.to_vec();
            path.push(word.to_owned());
            paths.push(path.join(" "));
        }
    }
    paths
}

/// The leading `bot a b c` path of a command cell, stopping at the first
/// argument, option or separator.
fn command_words(text: &str) -> Vec<String> {
    let mut words = text.split_whitespace();
    if words.next() != Some("bot") {
        return Vec::new();
    }
    let mut path = vec!["bot".to_owned()];
    for word in words {
        let word = word.trim_matches('`').trim_end_matches(',');
        if !is_command_word(word) {
            break;
        }
        path.push(word.to_owned());
    }
    if path.len() > 1 { path } else { Vec::new() }
}

fn is_command_word(word: &str) -> bool {
    !word.is_empty()
        && word
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_lowercase())
        && word
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

/// The first cell of a markdown table row, stopping at the first unescaped
/// `|` so paths such as `--role <phone\|desktop>` keep their backticks.
fn first_cell(line: &str) -> Option<&str> {
    let row = line.trim().strip_prefix('|')?;
    let mut escaped = false;
    for (index, character) in row.char_indices() {
        if escaped {
            escaped = false;
        } else if character == '\\' {
            escaped = true;
        } else if character == '|' {
            return Some(row[..index].trim());
        }
    }
    None
}

/// A command-table row. Full rows start with `bot`; rows such as
/// `` `setup [--token-env <VAR>]` `` are relative to the section's heading.
fn table_row_path(line: &str, section: &str) -> Option<String> {
    let cell = first_cell(line)?;
    let code = cell.strip_prefix('`')?.strip_suffix('`')?;
    let words = command_words(code);
    if !words.is_empty() {
        return Some(words.join(" "));
    }
    let word = code.split_whitespace().next()?;
    is_command_word(word).then(|| format!("{section} {word}"))
}

fn mentions_flag(text: &str, flag: &str) -> bool {
    text.match_indices(flag).any(|(start, _)| {
        let before = text[..start].chars().next_back();
        let after = text[start + flag.len()..].chars().next();
        !before.is_some_and(|c| c.is_alphanumeric() || c == '-')
            && !after.is_some_and(|c| c.is_alphanumeric() || c == '-')
    })
}

#[test]
fn documented_commands_match_the_cli() {
    let reference = Reference::parse();
    let mut cli = BTreeMap::new();
    collect(&mut Vec::new(), &mut cli);

    let allowed: BTreeSet<&str> = ALLOWED_MISSING.iter().map(|(path, _)| *path).collect();
    let mut problems = Vec::new();

    for (path, help) in &cli {
        if !help.children.is_empty() || allowed.contains(path.as_str()) {
            continue;
        }
        if !reference.commands.contains_key(path) {
            problems.push(format!(
                "`{path}` is a visible command but has no heading or command-table row in docs/guide/cli-reference.md"
            ));
        }
    }

    for (path, line) in &reference.commands {
        if !cli.contains_key(path) {
            problems.push(format!(
                "docs/guide/cli-reference.md:{line} documents `{path}`, but `bot --help` does not know it"
            ));
        }
    }

    for (path, reason) in ALLOWED_MISSING {
        assert!(
            cli.contains_key(*path),
            "allow-list entry `{path}` is not a real command"
        );
        assert!(
            !reason.trim().is_empty(),
            "allow-list entry `{path}` needs a reason"
        );
    }

    assert!(
        problems.is_empty(),
        "CLI reference drift:\n{}",
        problems.join("\n")
    );
}

#[test]
fn help_and_reference_parsers_handle_clap_layouts() {
    assert_eq!(
        option_flag("      --data-dir <DATA_DIR>"),
        Some("--data-dir")
    );
    assert_eq!(option_flag("  -h, --help  Print help"), Some("--help"));
    assert_eq!(option_flag("          A wrapped description"), None);
    assert_eq!(
        env_name("      Directory with catalog files [env: BOT_CATALOG_DIR=]"),
        Some("BOT_CATALOG_DIR")
    );
    assert_eq!(
        heading_paths("`bot backup create | verify | restore`"),
        vec![
            "bot backup create".to_owned(),
            "bot backup verify".to_owned(),
            "bot backup restore".to_owned(),
        ]
    );
    assert_eq!(
        table_row_path("| `bot providers list` | List |", "bot providers"),
        Some("bot providers list".to_owned())
    );
    assert_eq!(
        table_row_path(
            "| `setup [--token-env <VAR>]` | Store the token |",
            "bot channels telegram"
        ),
        Some("bot channels telegram setup".to_owned())
    );
    assert_eq!(table_row_path("| `--json` | JSON output |", "bot"), None);
}

fn check_flags_and_env(
    reference: &Reference<'_>,
    cli: &BTreeMap<String, Help>,
    allowed_flags: &[(&str, &str, &str)],
    allowed_env: &[(&str, &str)],
) -> Vec<String> {
    let Some(root) = cli.get("bot") else {
        panic!("`bot --help` produced no root command");
    };
    let inherited_global: BTreeSet<&str> = root
        .flags
        .iter()
        .map(String::as_str)
        .filter(|&f| f != "--help" && f != "--version")
        .collect();
    let mut problems = Vec::new();

    for flag in &root.flags {
        if flag == "--help" || flag == "--version" {
            continue;
        }
        let allowed = allowed_flags
            .iter()
            .any(|(path, f, _)| *path == "bot" && *f == flag.as_str());
        if !allowed && !mentions_flag(&reference.global_options, flag) {
            problems.push(format!(
                "`bot` has global flag `{flag}`, but `## Global options` in docs/guide/cli-reference.md does not mention it"
            ));
        }
    }

    for (path, help) in cli {
        if path == "bot" {
            continue;
        }
        let Some(body) = reference.section(path) else {
            continue;
        };
        for flag in &help.flags {
            if inherited_global.contains(flag.as_str()) || flag == "--help" {
                continue;
            }
            if allowed_flags.iter().any(|(allowed_path, allowed_flag, _)| {
                *allowed_path == path.as_str() && *allowed_flag == flag.as_str()
            }) {
                continue;
            }
            if !mentions_flag(body, flag) {
                problems.push(format!(
                    "`{path}` has `{flag}`, but its reference section does not mention it"
                ));
            }
        }
    }

    let mut envs = BTreeSet::new();
    for help in cli.values() {
        envs.extend(help.env.iter().map(String::as_str));
    }
    for &name in &envs {
        let allowed = allowed_env
            .iter()
            .any(|(allowed_name, _)| *allowed_name == name);
        if !allowed && !reference.text.contains(name) {
            problems.push(format!(
                "environment variable `{name}` is read by the CLI but missing from docs/guide/cli-reference.md"
            ));
        }
    }

    problems
}

/// Render a deterministic Markdown snapshot of the `bot` clap command tree.
fn render_generated_reference(cli: &BTreeMap<String, Help>) -> String {
    let Some(root) = cli.get("bot") else {
        panic!("`bot --help` produced no root command");
    };
    let inherited_global: BTreeSet<&str> = root
        .flags
        .iter()
        .map(String::as_str)
        .filter(|&f| f != "--help" && f != "--version")
        .collect();
    let mut envs = BTreeSet::new();
    for help in cli.values() {
        envs.extend(help.env.iter().map(String::as_str));
    }

    let mut out = String::new();
    out.push_str("# Generated CLI Reference (`bot`)\n\n");
    out.push_str(
        "Generated from the `clap` command definitions in `apps/cli/src/main.rs`.\n\
         Do not edit by hand; regenerate with:\n\n\
         ```sh\n\
         UPDATE_CLI_REFERENCE=1 cargo test -p cli --test cli_reference\n\
         ```\n\n\
         For usage prose and examples, see [`docs/guide/cli-reference.md`](../guide/cli-reference.md).\n\n",
    );

    out.push_str("## Global Options\n\n");
    for flag in &root.flags {
        let _ = writeln!(out, "- `{flag}`");
    }

    out.push_str("\n## Environment Variables\n\n");
    for env in &envs {
        let _ = writeln!(out, "- `{env}`");
    }

    out.push_str("\n## Command Tree\n\n");
    out.push_str("| Command | Summary | Subcommands | Options |\n");
    out.push_str("| --- | --- | --- | --- |\n");
    for (path, help) in cli {
        let subcommands: Vec<String> = help
            .children
            .iter()
            .filter(|c| c.as_str() != "help")
            .map(|c| format!("`{c}`"))
            .collect();
        let sub_cell = if subcommands.is_empty() {
            "—".to_owned()
        } else {
            subcommands.join(", ")
        };
        let local_flags: Vec<String> = help
            .flags
            .iter()
            .filter(|f| {
                let s = f.as_str();
                s != "--help"
                    && !(path == "bot" && s == "--version")
                    && s != "--fake-provider"
                    && (path == "bot" || !inherited_global.contains(s))
            })
            .map(|f| format!("`{f}`"))
            .collect();
        let opt_cell = if local_flags.is_empty() {
            "—".to_owned()
        } else {
            local_flags.join(", ")
        };
        let about = help.about.replace('|', "\\|");
        let _ = writeln!(out, "| `{path}` | {about} | {sub_cell} | {opt_cell} |");
    }
    out
}

#[test]
fn documented_flags_and_environment_match_the_cli() {
    let reference = Reference::parse();
    let mut cli = BTreeMap::new();
    collect(&mut Vec::new(), &mut cli);

    let Some(root) = cli.get("bot") else {
        panic!("`bot --help` produced no root command");
    };
    let mut envs = BTreeSet::new();
    for help in cli.values() {
        envs.extend(help.env.iter().map(String::as_str));
    }

    let problems =
        check_flags_and_env(&reference, &cli, ALLOWED_MISSING_FLAGS, ALLOWED_MISSING_ENV);

    for (path, flag, reason) in ALLOWED_MISSING_FLAGS {
        let exists = if *path == "bot" {
            root.flags.contains(*flag)
        } else {
            cli.get(*path)
                .is_some_and(|help| help.flags.contains(*flag))
        };
        assert!(
            exists,
            "allow-list entry `{path} {flag}` is not a real command flag"
        );
        assert!(
            !reason.trim().is_empty(),
            "allow-list entry `{path} {flag}` needs a reason"
        );
    }
    for (name, reason) in ALLOWED_MISSING_ENV {
        assert!(
            envs.contains(name),
            "allow-list entry `{name}` is not a real environment variable"
        );
        assert!(
            !reason.trim().is_empty(),
            "allow-list entry `{name}` needs a reason"
        );
    }

    assert!(
        problems.is_empty(),
        "CLI reference drift:\n{}",
        problems.join("\n")
    );
}

#[test]
fn generated_cli_reference_matches_command_tree() {
    let mut cli = BTreeMap::new();
    collect(&mut Vec::new(), &mut cli);
    let expected = render_generated_reference(&cli);
    let snapshot = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(GENERATED_CLI_REFERENCE_PATH);
    if std::env::var_os("UPDATE_CLI_REFERENCE").is_some() {
        if let Some(parent) = snapshot.parent() {
            std::fs::create_dir_all(parent).expect("create docs/cli directory");
        }
        std::fs::write(&snapshot, &expected).expect("write generated CLI reference");
    }
    let actual = std::fs::read_to_string(&snapshot)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", snapshot.display()))
        .replace("\r\n", "\n");
    assert_eq!(
        actual, expected,
        "{GENERATED_CLI_REFERENCE_PATH} is out of date with the `bot` clap command tree; \
         run `UPDATE_CLI_REFERENCE=1 cargo test -p cli --test cli_reference` and commit the result"
    );
}

#[test]
fn drift_detector_reports_missing_global_flags_subcommand_flags_and_env() {
    let doc = "\
# CLI reference
## Global options
| `--data-dir <PATH>` | `BOT_DATA_DIR` |
## Commands
### `bot status`
Show daemon status.
";
    let reference = Reference::parse_str(doc);
    let mut cli = BTreeMap::new();
    cli.insert(
        "bot".to_owned(),
        Help {
            about: "Root".to_owned(),
            children: vec!["status".to_owned()],
            flags: BTreeSet::from(["--data-dir".to_owned(), "--new-global".to_owned()]),
            env: BTreeSet::from(["BOT_DATA_DIR".to_owned(), "BOT_NEW_ENV".to_owned()]),
        },
    );
    cli.insert(
        "bot status".to_owned(),
        Help {
            about: "Status".to_owned(),
            children: Vec::new(),
            flags: BTreeSet::from(["--data-dir".to_owned(), "--new-local".to_owned()]),
            env: BTreeSet::new(),
        },
    );

    let problems = check_flags_and_env(&reference, &cli, &[], &[]);
    assert_eq!(problems.len(), 3, "{problems:?}");
    assert!(problems.iter().any(|p| p.contains("--new-global")));
    assert!(problems.iter().any(|p| p.contains("--new-local")));
    assert!(problems.iter().any(|p| p.contains("BOT_NEW_ENV")));
}
