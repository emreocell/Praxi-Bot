#!/usr/bin/env python3
r"""Generate crates/secret-store/src/rules.rs from gitleaks' default config.

Usage:
    python scripts/tools/gen_secret_rules.py <gitleaks.toml> [--commit <sha>] [--out <rules.rs>]

Download the input yourself, e.g.
    curl -L https://raw.githubusercontent.com/gitleaks/gitleaks/<sha>/config/gitleaks.toml

gitleaks is MIT licensed, Copyright (c) 2019 Zachary Rice. The generated file
carries that notice (see also THIRD_PARTY_NOTICES.md). Rules we leave out:
  * rules without a regex (file-name-only rules such as `pkcs12-file`);
  * rules restricted to a file path (`path = ...`): we scan chat text and tool
    output, not files, so a path-gated rule would fire everywhere;
  * `generic-api-key`: entropy-only context guessing is too noisy for text
    that is mostly prose (detect.rs has its own labelled-value detector).
`\w`, `\d`, `\b` are rewritten to their ASCII forms (Go semantics).
Rule-level allowlists are kept only when they test the secret itself (the
default target) and have no path condition.
"""
import argparse
import pathlib
import sys
import tomllib

SKIP_IDS = {"generic-api-key"}


def ascii_classes(rx: str) -> str:
    r"""Make `\w`, `\d` and `\b` ASCII-only, as they are in Go's RE2.

    Rust's are Unicode-aware, which is not what gitleaks meant and makes rules
    such as `[\w-]{50,1000}` far too big to compile.
    """
    out = []
    i = 0
    in_class = False
    while i < len(rx):
        c = rx[i]
        if c == "\\" and i + 1 < len(rx):
            n = rx[i + 1]
            if n == "w":
                out.append("0-9A-Za-z_" if in_class else "[0-9A-Za-z_]")
            elif n == "d":
                out.append("0-9" if in_class else "[0-9]")
            elif n == "b" and not in_class:
                out.append(r"(?-u:\b)")
            else:
                out.append(c + n)
            i += 2
            continue
        if not in_class and c == "[":
            in_class = True
            out.append(c)
            i += 1
            if i < len(rx) and rx[i] == "^":
                out.append("^")
                i += 1
            if i < len(rx) and rx[i] == "]":
                out.append("]")
                i += 1
            continue
        if in_class and c == "[" and rx.startswith("[:", i):
            end = rx.find(":]", i)
            if end != -1:
                out.append(rx[i : end + 2])
                i = end + 2
                continue
        if in_class and c == "]":
            in_class = False
        out.append(c)
        i += 1
    return "".join(out)


def raw(s: str) -> str:
    n = 0 if '"' not in s else 1
    while '"' + "#" * n in s:
        n += 1
    return 'r' + "#" * n + '"' + s + '"' + "#" * n


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("toml")
    ap.add_argument("--commit", default="unknown")
    root = pathlib.Path(__file__).resolve().parents[2]
    ap.add_argument("--out", default=str(root / "crates/secret-store/src/rules.rs"))
    args = ap.parse_args()

    with open(args.toml, "rb") as f:
        cfg = tomllib.load(f)

    rows = []
    for r in cfg["rules"]:
        if "regex" not in r or "path" in r or r["id"] in SKIP_IDS:
            continue
        allow = []
        for al in r.get("allowlists", []):
            if al.get("regexTarget", "secret") != "secret":
                continue
            if "paths" in al or "stopwords" in al or al.get("condition", "OR") != "OR":
                continue
            allow += [ascii_classes(x) for x in al.get("regexes", [])]
        rows.append((r, sorted(set(allow))))
    rows.sort(key=lambda t: t[0]["id"])

    out = [
        "// @generated by scripts/tools/gen_secret_rules.py -- DO NOT EDIT BY HAND.",
        "//",
        f"// Source: gitleaks config/gitleaks.toml at commit {args.commit}",
        "// https://github.com/gitleaks/gitleaks",
        "//",
        "// Adapted from gitleaks (MIT License), Copyright (c) 2019 Zachary Rice.",
        "// Permission is hereby granted, free of charge, to any person obtaining a copy of",
        "// this software and associated documentation files (the \"Software\"), to deal in",
        "// the Software without restriction, including without limitation the rights to",
        "// use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of",
        "// the Software, subject to the above copyright notice and this permission notice",
        "// being included in all copies or substantial portions of the Software. THE",
        "// SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND. The full licence",
        "// text is in THIRD_PARTY_NOTICES.md.",
        "//",
        "// Changes by Praxi-Bot: converted from TOML to a Rust table; dropped path-gated",
        "// rules, `generic-api-key` and rule allowlists that do not test the secret itself.",
        "",
        "use crate::scan::Rule;",
        "",
        "/// Every converted rule, sorted by id.",
        "pub(crate) static RULES: &[Rule] = &[",
    ]
    for r, allow in rows:
        kws = ", ".join(raw(k.lower()) for k in r.get("keywords", []))
        al = ", ".join(raw(a) for a in allow)
        out += [
            "    Rule {",
            f"        id: {raw(r['id'])},",
            f"        description: {raw(r['description'])},",
            f"        regex: {raw(ascii_classes(r['regex']))},",
            f"        keywords: &[{kws}],",
            f"        entropy: {float(r.get('entropy', 0)):.2f},",
            f"        secret_group: {int(r.get('secretGroup', 0))},",
            f"        allow: &[{al}],",
            "    },",
        ]
    out += ["];", ""]
    pathlib.Path(args.out).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} rules to {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
