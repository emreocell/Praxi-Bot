#!/usr/bin/env node
// Regenerates lib/icons-data.mjs from the lucide-static and simple-icons npm packages.
// Only needed when the icon list below changes; the normal build does not use it.
//
//   mkdir /tmp/icons && cd /tmp/icons && npm i lucide-static simple-icons
//   node extract-icons.mjs /tmp/icons/node_modules
//
// lucide-static is ISC licensed, simple-icons is CC0 1.0 (brand marks stay the
// property of their owners and are used here only to name integrations).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const modules = process.argv[2];
if (!modules) throw new Error('usage: node extract-icons.mjs <path to node_modules>');

const lucide = [
  'mouse-pointer-click', 'workflow', 'shield-check', 'cpu', 'blocks', 'network', 'calendar-clock', 'send',
  'app-window', 'terminal', 'server', 'lock-keyhole', 'database', 'hand', 'laptop', 'cloud', 'key-round',
  'mail', 'house', 'globe', 'folder', 'download', 'bot', 'scale', 'file-text', 'monitor', 'play', 'check',
  'plug', 'clock', 'brain-circuit', 'sliders-horizontal', 'message-square', 'history', 'hard-drive',
  'sparkles', 'git-fork', 'eye', 'ban', 'repeat', 'wrench', 'lock', 'router',
];
const brands = [
  'rust', 'telegram', 'tauri', 'ollama', 'lmstudio', 'anthropic', 'googlegemini', 'openrouter', 'deepseek',
  'modelcontextprotocol', 'sqlite', 'linux',
];

const inner = svg => svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  .replace(/\s+/g, ' ').replace(/> </g, '><').trim();
const lucideVersion = JSON.parse(readFileSync(join(modules, 'lucide-static/package.json'), 'utf8')).version;
const simpleVersion = JSON.parse(readFileSync(join(modules, 'simple-icons/package.json'), 'utf8')).version;
const lu = Object.fromEntries(lucide.map(name => [name,
  inner(readFileSync(join(modules, 'lucide-static/icons', name + '.svg'), 'utf8'))]));
const br = Object.fromEntries(brands.map(name => {
  const svg = readFileSync(join(modules, 'simple-icons/icons', name + '.svg'), 'utf8');
  const d = svg.match(/<path d="([^"]+)"/);
  if (!d) throw new Error('no path in ' + name);
  return [name, d[1]];
}));
const out = '// Generated by extract-icons.mjs. Do not edit by hand.\n'
  + '// lucide-static ' + lucideVersion + ' (ISC): 24x24 stroke icons, inner SVG markup.\n'
  + '// simple-icons ' + simpleVersion + ' (CC0-1.0): 24x24 filled brand marks, path data.\n'
  + 'export const lucide = ' + JSON.stringify(lu, null, 1) + ';\n\n'
  + 'export const brands = ' + JSON.stringify(br, null, 1) + ';\n';
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'lib/icons-data.mjs'), out);
console.log('wrote lib/icons-data.mjs', Object.keys(lu).length, 'lucide,', Object.keys(br).length, 'brands');
