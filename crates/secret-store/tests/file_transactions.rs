use std::{path::Path, sync::Arc};

use secret_store::{EncryptedFileStore, KdfParams, SecretStore};

fn store(dir: &Path) -> EncryptedFileStore {
    EncryptedFileStore::new(dir.join("secrets.enc"), "fixture-passphrase").with_kdf(KdfParams {
        m_cost: 8,
        t_cost: 1,
        p_cost: 1,
    })
}

fn assert_no_temps(dir: &Path) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        assert!(
            !entry.file_name().to_string_lossy().ends_with(".tmp"),
            "leftover temporary file: {}",
            entry.path().display()
        );
    }
}

#[test]
fn existing_shared_temp_is_never_truncated_or_renamed() {
    let dir = tempfile::tempdir().unwrap();
    let existing = dir.path().join("secrets.tmp");
    std::fs::write(&existing, b"another writer owns this file").unwrap();
    let store = store(dir.path());
    store.set("compat.name", "fixture-value").unwrap();
    assert_eq!(
        std::fs::read(existing).unwrap(),
        b"another writer owns this file"
    );
}

#[test]
fn concurrent_set_of_640_distinct_names_keeps_every_value() {
    let dir = tempfile::tempdir().unwrap();
    let store = Arc::new(store(dir.path()));
    let start = Arc::new(std::sync::Barrier::new(32));
    std::thread::scope(|threads| {
        for thread in 0..32 {
            let store = Arc::clone(&store);
            let start = Arc::clone(&start);
            threads.spawn(move || {
                start.wait();
                for i in 0..20 {
                    let name = format!("thread-{thread}-{i}");
                    store.set(&name, &name).unwrap();
                }
            });
        }
    });
    assert_eq!(store.list_names().unwrap().len(), 640);
    store.verify().unwrap();
    for thread in 0..32 {
        for i in 0..20 {
            let name = format!("thread-{thread}-{i}");
            assert_eq!(store.get(&name).unwrap().unwrap().expose(), name);
        }
    }
    assert_no_temps(dir.path());
}

#[test]
fn separate_handles_serialize_interleaved_set_and_delete() {
    let dir = tempfile::tempdir().unwrap();
    let initial = store(dir.path());
    for handle in 0..2 {
        for i in 0..20 {
            initial.set(&format!("remove-{handle}-{i}"), "old").unwrap();
        }
    }
    let start = std::sync::Barrier::new(2);
    std::thread::scope(|threads| {
        for handle in 0..2 {
            let writer = store(dir.path());
            let start = &start;
            threads.spawn(move || {
                start.wait();
                for i in 0..20 {
                    writer.set(&format!("keep-{handle}-{i}"), "new").unwrap();
                    assert!(writer.delete(&format!("remove-{handle}-{i}")).unwrap());
                }
            });
        }
    });
    let names = initial.list_names().unwrap();
    assert_eq!(names.len(), 40);
    assert!(names.iter().all(|name| name.starts_with("keep-")));
    assert_no_temps(dir.path());
}

#[test]
fn encrypted_file_from_pretransaction_backend_remains_compatible() {
    let dir = tempfile::tempdir().unwrap();
    let store = store(dir.path());
    // Generated by EncryptedFileStore at bdc8d8c, before the atomic-write fix.
    std::fs::write(store.path(), include_str!("fixtures/v1-secrets.enc.json")).unwrap();
    store.verify().unwrap();
    assert_eq!(store.list_names().unwrap(), ["compat.name"]);
    assert_eq!(
        store.get("compat.name").unwrap().unwrap().expose(),
        "fixture-value"
    );
    store.set("new", "still-v1").unwrap();
    let raw: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(store.path()).unwrap()).unwrap();
    assert_eq!(raw["version"], 1);
    assert_eq!(
        store.get("compat.name").unwrap().unwrap().expose(),
        "fixture-value"
    );
}

#[test]
fn two_processes_keep_every_update_and_remove_their_temps() {
    let dir = tempfile::tempdir().unwrap();
    let mut children = Vec::new();
    for id in 0..2 {
        children.push(
            std::process::Command::new(std::env::current_exe().unwrap())
                .args(["--exact", "child_process_writer", "--ignored"])
                .env("PRAXI_SECRET_TEST_DIR", dir.path())
                .env("PRAXI_SECRET_TEST_WRITER", id.to_string())
                .stdout(std::process::Stdio::piped())
                .stderr(std::process::Stdio::piped())
                .spawn()
                .unwrap(),
        );
    }
    for child in children {
        let output = child.wait_with_output().unwrap();
        assert!(
            output.status.success(),
            "child failed: {}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    assert_eq!(store(dir.path()).list_names().unwrap().len(), 40);
    assert_no_temps(dir.path());
}

#[test]
#[ignore = "subprocess helper for two_processes_keep_every_update_and_remove_their_temps"]
fn child_process_writer() {
    let dir = std::env::var_os("PRAXI_SECRET_TEST_DIR").unwrap();
    let id = std::env::var("PRAXI_SECRET_TEST_WRITER").unwrap();
    let store = store(Path::new(&dir));
    for i in 0..20 {
        let name = format!("process-{id}-{i}");
        store.set(&name, &name).unwrap();
        let deleted = format!("temporary-{id}-{i}");
        store.set(&deleted, "value").unwrap();
        assert!(store.delete(&deleted).unwrap());
    }
}
